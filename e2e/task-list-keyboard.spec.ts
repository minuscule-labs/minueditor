test('task items continue, exit, indent, and expose raw syntax in source mode', async ({ page }) => {
  await page.goto('/?fixture=task-list-keyboard')
  const editor = page.locator('.cm-content')
  const markdown = page.getByTestId('markdown-output')
  await editor.press('End')
  await editor.press('Enter')
  await expect(markdown).toHaveText('- [ ] one\n- [ ] ')
  await editor.press('Enter')
  await expect(markdown).toHaveText('- [ ] one\n')

  await page.getByRole('button', { name: 'Reset nested task' }).click()
  await expect(markdown).toHaveText('- parent\n- [ ] one')
  await page.getByRole('button', { name: 'Focus task end' }).click()
  await expect(page.getByTestId('selection-offset')).toHaveText('18')
  await editor.press('Tab')
  await expect(markdown).toHaveText('- parent\n    - [ ] one')
  await expect(page.getByTestId('selection-offset')).toHaveText('22')
  await editor.press('Shift+Tab')
  await expect(markdown).toHaveText('- parent\n- [ ] one')
  await expect(page.getByTestId('selection-offset')).toHaveText('18')

  await page.getByRole('button', { name: 'Reset task' }).click()
  await page.getByRole('button', { name: 'Mode: live' }).click()
  await expect(page.locator('.me-checkbox')).toHaveCount(0)
  await editor.click()
  await editor.press('Home')
  await editor.press('ArrowRight')
  await editor.press('ArrowRight')
  await editor.press('Delete')
  await expect(markdown).toHaveText('-  ] one')

  await page.getByRole('button', { name: 'Reset task' }).click()
  await expect(markdown).toHaveText('- [ ] one')
  await page.getByRole('button', { name: 'Focus task end' }).click()
  await editor.press('Home')
  for (let i = 0; i < 6; i++) await editor.press('ArrowRight')
  await expect(page.getByTestId('selection-offset')).toHaveText('6')
  await editor.press('Backspace')
  await expect(markdown).toHaveText('- [ ]one')
})

test('live Tab keeps a lone top-level item a list while source Tab edits raw Markdown', async ({ page }) => {
  await page.goto('/?fixture=task-list-keyboard')
  const editor = page.locator('.cm-content')
  const markdown = page.getByTestId('markdown-output')
  for (const [button, value] of [['Reset task', '- [ ] one'], ['Reset bullet', '- one']]) {
    await page.getByRole('button', { name: button, exact: true }).click()
    await page.getByRole('button', { name: 'Focus task end' }).click()
    await editor.press('Tab')
    await expect(markdown).toHaveText(value)
    await expect(editor).toBeFocused()
    await editor.press('Shift+Tab')
    await expect(markdown).toHaveText(value)
    await expect(editor).toBeFocused()
  }

  await page.getByRole('button', { name: 'Reset task', exact: true }).click()
  await page.getByRole('button', { name: 'Mode: live' }).click()
  await page.getByRole('button', { name: 'Focus task end' }).click()
  await editor.press('Tab')
  await expect(markdown).toHaveText('    - [ ] one')
})


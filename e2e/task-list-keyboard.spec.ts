test('selection and word deletion cannot expose part of a live task checkbox', async ({ page }) => {
  await page.goto('/?fixture=task-list-keyboard')
  const editor = page.locator('.cm-content')
  const markdown = page.getByTestId('markdown-output')
  const offset = page.getByTestId('selection-offset')

  for (const keys of [
    ['Shift+ArrowLeft', 'Backspace'],
    ['Shift+ArrowLeft', 'Shift+ArrowLeft', 'Backspace'],
    ['ArrowLeft', 'Shift+ArrowRight', 'Delete'],
    ['Shift+Home', 'Backspace'],
    ['Alt+Backspace'],
    ['ControlOrMeta+Backspace'],
  ]) {
    await page.getByRole('button', { name: 'Reset task', exact: true }).click()
    await page.getByRole('button', { name: 'Focus task end' }).click()
    await editor.press('Home')
    await expect(offset).toHaveText('6')
    for (const key of keys) await editor.press(key)
    await expect(markdown).toHaveText('one')
    await expect(page.locator('.me-checkbox')).toHaveCount(0)
  }
})

test('entering live mode moves a source caret out of hidden checkbox syntax', async ({ page }) => {
  await page.goto('/?fixture=task-list-keyboard')
  const editor = page.locator('.cm-content')
  const markdown = page.getByTestId('markdown-output')
  const offset = page.getByTestId('selection-offset')
  await page.getByRole('button', { name: 'Mode: live' }).click()
  await page.getByRole('button', { name: 'Focus task end' }).click()
  await editor.press('Home')
  for (let i = 0; i < 3; i++) await editor.press('ArrowRight')
  await expect(offset).toHaveText('3')
  await page.getByRole('button', { name: 'Mode: source' }).click()
  await expect(page.locator('.me-checkbox')).toHaveCount(1)
  await expect(offset).toHaveText('6')
  await page.getByRole('button', { name: 'Restore editor focus' }).click()
  await editor.press('Z')
  await expect(markdown).toHaveText('- [ ] Zone')
})


import { expect, test } from '@playwright/test'

test('task markers stay atomic for Home, arrow navigation, Backspace, and Delete', async ({ page }) => {
  await page.goto('/?fixture=task-list-keyboard')
  const editor = page.locator('.cm-content')
  const markdown = page.getByTestId('markdown-output')
  const offset = page.getByTestId('selection-offset')
  await editor.press('End')
  await editor.press('Home')
  await expect(offset).toHaveText('6')
  await editor.press('ArrowLeft')
  await expect(offset).toHaveText('0')
  await editor.press('ArrowRight')
  await expect(offset).toHaveText('6')
  await editor.press('Backspace')
  await expect(markdown).toHaveText('one')
  await expect(offset).toHaveText('0')
  await editor.press('ControlOrMeta+z')
  await expect(markdown).toHaveText('- [ ] one')
  await editor.press('ControlOrMeta+Shift+z')
  await expect(markdown).toHaveText('one')
  await editor.type('N')
  await expect(markdown).toHaveText('None')

  await page.getByRole('button', { name: 'Reset task' }).click()
  await editor.press('End')
  await editor.press('Home')
  await editor.press('ArrowLeft')
  await editor.press('Delete')
  await expect(markdown).toHaveText('one')
  await expect(offset).toHaveText('0')
})

